import {build} from 'esbuild';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
await build({entryPoints:['lib/feeds.ts'],bundle:true,platform:'node',format:'esm',outfile:'outputs/feeds-check.mjs'});
const feeds=await import('../outputs/feeds-check.mjs');
const rss=await readFile('tests/fixtures/behance.xml','utf8');
const scholar=await readFile('tests/fixtures/scholar.html','utf8');
const result=feeds.parseBehance(rss);
assert.equal(result.items.length,8,'Curated selection remains eight');
assert.equal(result.matched,4,'Four selected projects match the current public feed');
assert(!result.items.some(p=>p.title.includes('Peachy')||p.title.includes('Chimera')),'Unselected work must not be published');
assert(result.items.find(p=>p.id==='siggraph').url.includes('108409107'));
assert(result.items.find(p=>p.id==='fundome').image.startsWith('/images/'),'Archive preserved for missing feed entries');
assert.throws(()=>feeds.parseBehance('<html>service unavailable</html>'));
const papers=feeds.parseScholar(scholar);assert.equal(papers.length,14);assert(papers.every(p=>p.url.startsWith('https://scholar.google.com/')));
const unsafe=feeds.parseBehance(rss.replaceAll('https://mir-s3-cdn-cf.behance.net/','https://untrusted.invalid/'));
assert(unsafe.items.every(p=>p.image.startsWith('/images/')),'Untrusted images excluded');
assert.equal(feeds.parseScholar('<html>captcha</html>').length,0,'Blocked responses cannot replace good data');
globalThis.fetch=async url=>new Response(String(url).includes('behance')?rss:scholar,{status:200});
assert.equal((await feeds.getProjects()).cached,false);assert.equal((await feeds.getPublications()).cached,false);
const fallback=await import('../outputs/feeds-check.mjs?fallback');
globalThis.fetch=async()=>{throw new Error('offline');};
assert.equal((await fallback.getProjects()).items.length,8);assert.equal((await fallback.getPublications()).items.length,14);assert.equal((await fallback.getPublications()).cached,true);
console.log('PASS: feed parsing, selection, URL safety, Scholar metadata, live refresh and offline fallback.');
